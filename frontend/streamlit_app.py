def _backend_url() -> str:
    """Read the backend URL from environment variables or Streamlit secrets."""
    secret_url = ""
    try:
        secret_url = st.secrets.get("BACKEND_URL", "")
    except Exception:
        # Streamlit secrets are optional in local development.
        pass
    return (
        os.getenv("BACKEND_URL", "").strip()
        or str(secret_url).strip()
        or "http://127.0.0.1:8000"
    ).rstrip("/")


def _client() -> ApiClient:
    return ApiClient(_backend_url())


def _set_page(page: str) -> None:
    st.session_state.page = page
