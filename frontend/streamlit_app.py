def _clear_upload_state() -> None:
    """Reset the upload widget and its associated caption result."""
    st.session_state["image_upload"] = None
    st.session_state.caption_result = None
    st.session_state.upload_fingerprint = None


def _timestamp(value: str) -> str:
    if not value:
        return "Date unavailable"
    return value.replace("T", " ").replace("+00:00", " UTC")[:22]


