def _validate_upload(image_bytes: bytes, filename: str) -> tuple[bool, str, tuple[int, int] | None]:
    extension = Path(filename).suffix.lower()
    if extension not in {".jpg", ".jpeg", ".png"}:
        return False, "Choose a JPG, JPEG, or PNG image.", None
    if len(image_bytes) > MAX_UPLOAD_BYTES:
        return False, "The image exceeds the configured upload limit.", None

    try:
        with warnings.catch_warnings():
            warnings.simplefilter("error", Image.DecompressionBombWarning)
            with Image.open(io.BytesIO(image_bytes)) as image:
                detected = image.format
                dimensions = image.size
                if dimensions[0] * dimensions[1] > MAX_IMAGE_PIXELS:
                    return False, "The image dimensions exceed the configured limit.", None
                expected = "PNG" if extension == ".png" else "JPEG"
                if detected != expected:
                    return False, "The file extension does not match the image contents.", None
                image.verify()
            with Image.open(io.BytesIO(image_bytes)) as image:
                image.load()
        return True, "", dimensions
    except (
        UnidentifiedImageError,
        OSError,
        Image.DecompressionBombError,
        Image.DecompressionBombWarning,
    ):
        return False, "This file is not a valid, readable image.", None


def _generate(client: ApiClient) -> None:
    st.markdown("## Generate a caption")
    st.write(
        f"Choose a JPG, JPEG, or PNG image up to "
        f"{MAX_UPLOAD_BYTES / (1024 * 1024):g} MB."
    )
    uploaded = st.file_uploader(
        "Drop an image here or browse your files",
        type=["jpg", "jpeg", "png"],
        accept_multiple_files=False,
        key="image_upload",
        help="The Flask API validates and processes the original image contents.",
    )
    if uploaded is None:
        if st.session_state.get("caption_result"):
            st.button("Clear current result", on_click=_clear_upload_state)
        st.info("Your image preview and caption will appear here after you choose a file.")
        return

    image_bytes = uploaded.getvalue()
    fingerprint = hashlib.sha256(image_bytes).hexdigest()
    if st.session_state.get("upload_fingerprint") != fingerprint:
        st.session_state.upload_fingerprint = fingerprint
        st.session_state.caption_result = None

    valid, validation_message, dimensions = _validate_upload(
        image_bytes, uploaded.name
    )
    if not valid:
        st.error(validation_message)
        return

    preview_col, info_col = st.columns([1.1, 1], gap="large")
    with preview_col:
        st.image(image_bytes, caption=uploaded.name, use_container_width=True)
    with info_col:
        st.markdown("### Image details")
        st.write("**Filename:**", uploaded.name)
        st.write(f"**Dimensions:** {dimensions[0]} × {dimensions[1]} px")
        st.write(f"**Size:** {len(image_bytes) / 1024:.0f} KB")

        result = st.session_state.get("caption_result")
        if result and result.get("fingerprint") == fingerprint:
            _show_caption(result["data"])

        if st.button(
            "Generate caption",
            type="primary",
            use_container_width=True,
            key="generate_caption",
        ):
            with st.spinner(
                "The vision model is generating a caption. Its first run may take "
                "longer while model files download."
            ):
                try:
                    data = client.generate_caption(uploaded.name, image_bytes)
                    st.session_state.caption_result = {
                        "fingerprint": fingerprint,
                        "data": data,
                    }
                    st.rerun()
                except ApiError as exc:
                    st.error(str(exc))

        st.button(
            "Clear upload and start again",
            key="clear_upload",
            on_click=_clear_upload_state,
        )


def _show_caption(record: dict) -> None:
    st.markdown("### Generated caption")
    st.markdown(
        f'<div class="caption-result">{escape(record["caption"])}</div>',
        unsafe_allow_html=True,
    )
    st.caption("Use the copy button on the code block below to copy the caption.")
    st.code(record["caption"], language=None)
    st.caption(f"Saved as {record.get('original_filename', record.get('filename', 'image'))}")


def _history(client: ApiClient) -> None:
    st.markdown("## Caption history")
    st.write("Every successful caption is saved here with its original image.")
    try:
        records = client.list_images()
    except ApiError as exc:
        st.error(str(exc))
        return

    if not records:
        st.info(
            "No captions saved yet. Generate a caption and it will appear here."
        )
        if st.button("Create your first caption", type="primary"):
            _set_page("Generate Caption")
        return

    st.caption(f"{len(records)} saved caption{'s' if len(records) != 1 else ''}")
    columns = st.columns(3, gap="medium")
    for index, record in enumerate(records):
        with columns[index % len(columns)]:
            with st.container(border=True):
                try:
                    image_bytes = client.get_image(record["id"])
                    st.image(
                        image_bytes,
                        use_container_width=True,
                        caption=record.get("original_filename", ""),
                    )
                except ApiError as exc:
                    st.warning(str(exc))

                st.write(record.get("caption", "Caption unavailable"))
                st.caption(
                    f"{record.get('original_filename', record.get('filename', 'Image'))}"
                    f" · {_timestamp(record.get('uploaded_at', ''))}"
                )
                with st.expander("View details"):
                    st.write(f"Stored filename: `{record.get('filename', '—')}`")
                    st.write(f"Record ID: `{record.get('id', '—')}`")

                record_id = record["id"]
                if st.session_state.get("delete_confirmation") == record_id:
                    st.warning("Delete this saved image and its caption?")
                    confirm_col, cancel_col = st.columns(2)
                    if confirm_col.button(
                        "Confirm delete", key=f"confirm-{record_id}", type="primary"
                    ):
                        try:
                            client.delete_image(record_id)
                            st.session_state.delete_confirmation = None
                            st.toast("Caption deleted.")
                            st.rerun()
                        except ApiError as exc:
                            st.error(str(exc))
                    if cancel_col.button("Cancel", key=f"cancel-{record_id}"):
                        st.session_state.delete_confirmation = None
                        st.rerun()
                elif st.button(
                    "Delete", key=f"delete-{record_id}", use_container_width=True
                ):
                    st.session_state.delete_confirmation = record_id
                    st.rerun()


